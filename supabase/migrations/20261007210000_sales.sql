alter table public.sales           enable row level security;
alter table public.sale_items      enable row level security;
alter table public.sale_item_costs enable row level security;

grant select on public.sales, public.sale_items, public.sale_item_costs to authenticated;

create policy "members with sales.read can select sales"
  on public.sales for select to authenticated
  using (business_id in (select private.businesses_with_permission('sales.read')));

create policy "members with sales.read_own can select their own sales"
  on public.sales for select to authenticated
  using (sold_by = (select auth.uid())
         and business_id in (select private.businesses_with_permission('sales.read_own')));

-- Lines follow the visibility of their sale (sales RLS applies in the subquery).
create policy "members can select lines of visible sales"
  on public.sale_items for select to authenticated
  using (exists (select 1 from public.sales s where s.business_id = sale_items.business_id and s.id = sale_items.sale_id));

create policy "members with products.read_cost can select sale costs"
  on public.sale_item_costs for select to authenticated
  using (business_id in (select private.businesses_with_permission('products.read_cost'))
         and business_id in (select private.businesses_with_permission('sales.read')));

create policy "members can select payments of visible sales"
  on public.payments for select to authenticated
  using (sale_id is not null
         and exists (select 1 from public.sales s where s.business_id = payments.business_id and s.id = payments.sale_id));

