-- =============================================================================
-- JËND PRO — Sales (Phase 9)
-- -----------------------------------------------------------------------------
-- * create_sale(): ONE transaction for number + lines + stock (SALE movements)
--   + payments (several methods) + credit part on the customer account.
--   Idempotent through client_reference (offline / retry safe).
-- * cancel_sale(): full cancellation — stock back (SALE_CANCELLATION), credit
--   reversed, refund as payment OUT. Sales are never edited or deleted.
-- * Prices always come from the catalog; reductions are explicit discounts
--   (sales.discount). Frozen unit costs live in sale_item_costs, readable only
--   with products.read_cost (cashiers never see margins).
-- See docs/business-rules.md §4.
-- =============================================================================

create type public.sale_status as enum ('COMPLETED', 'CANCELLED');

-- -----------------------------------------------------------------------------
-- sales
-- -----------------------------------------------------------------------------
create table public.sales (
  id               uuid primary key default gen_random_uuid(),
  business_id      uuid not null references public.businesses (id),
  number           text not null,
  -- Generated by the app for each sale; a retried request returns the same sale.
  client_reference uuid not null,
  location_id      uuid not null,
  customer_id      uuid,
  status           public.sale_status not null default 'COMPLETED',
  subtotal_amount  bigint not null check (subtotal_amount >= 0),
  discount_amount  bigint not null default 0 check (discount_amount >= 0),
  total_amount     bigint not null check (total_amount >= 0),
  -- Paid at checkout (sum of IN payments of the sale).
  amount_paid      bigint not null default 0 check (amount_paid >= 0),
  -- Left on the customer account.
  credit_amount    bigint not null default 0 check (credit_amount >= 0),
  payment_status   public.payment_status generated always as (private.payment_status(amount_paid, total_amount)) stored,
  notes            text check (char_length(notes) <= 500),
  sold_at          timestamptz not null default now(),
  sold_by          uuid default auth.uid() references auth.users (id) on delete set null,
  cancelled_at     timestamptz,
  cancelled_by     uuid references auth.users (id) on delete set null,
  cancel_reason    text check (char_length(cancel_reason) <= 500),
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  constraint sales_business_id_id_key unique (business_id, id),
  constraint sales_business_id_number_key unique (business_id, number),
  constraint sales_business_id_client_reference_key unique (business_id, client_reference),
  constraint sales_location_fkey foreign key (business_id, location_id)
    references public.locations (business_id, id),
  constraint sales_customer_fkey foreign key (business_id, customer_id)
    references public.customers (business_id, id),
  constraint sales_total_consistency_check check (total_amount = subtotal_amount - discount_amount),
  constraint sales_settlement_consistency_check check (amount_paid + credit_amount = total_amount),
  constraint sales_credit_customer_required_check check (credit_amount = 0 or customer_id is not null),
  constraint sales_cancelled_consistency_check check ((status = 'CANCELLED') = (cancelled_at is not null))
);

comment on table public.sales is 'Sales. Written only by create_sale() / cancel_sale().';

-- Sales journal, customer history, cashier's own sales.
create index sales_business_id_sold_at_idx on public.sales (business_id, sold_at desc);
create index sales_business_id_customer_id_idx on public.sales (business_id, customer_id) where customer_id is not null;
create index sales_business_id_sold_by_idx on public.sales (business_id, sold_by, sold_at desc);

create trigger set_updated_at
  before update on public.sales
  for each row execute function private.set_updated_at();

